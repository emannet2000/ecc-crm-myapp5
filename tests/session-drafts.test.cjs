'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const {parseHTML}=require('linkedom');
const vm=require('node:vm');
const fs=require('node:fs');
const source=fs.readFileSync(require('node:path').join(__dirname,'../public/session-drafts.js'),'utf8');
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
test('session drafts restore only for the same account and record, exclude sensitive controls, and require review',async()=>{
 const {window}=parseHTML('<html><body><nav id="workspace-navigation" data-user-id="owner-a"></nav><div id="app"></div></body></html>');
 const {document}=window,values=new Map();
 const sessionStorage={getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
 const mount=(id='case-one')=>{const host=document.createElement('crm-case-test');host.setAttribute('record-id',id);host.attachShadow({mode:'open'}).innerHTML='<form><input name="title" value="Latest saved value"><textarea name="notes"></textarea><input name="password" type="password"><input name="consent" type="checkbox"><input name="upload" type="file"><input name="secret" value="private"><button type="submit">Save</button></form>';document.querySelector('#app').replaceChildren(host);return host.shadowRoot.querySelector('form')};
 let form=mount();
 vm.runInNewContext(source,{window,document,sessionStorage,location:{pathname:'/cases/case-one'},MutationObserver:window.MutationObserver,Event:window.Event,queueMicrotask});
 form.querySelector('[name=title]').value='Unsaved title';form.querySelector('[name=notes]').value='Unsaved notes';form.querySelector('[name=password]').value='Never save this';form.querySelector('[name=consent]').checked=true;
 window.CRMSessionDrafts.capture('owner-a');
 assert.ok(![...values.values()].join('').includes('Never save this'));
 assert.ok(![...values.values()].join('').includes('secret'));
 form=mount('different-record');await tick();assert.equal(form.querySelector('[data-session-recovery]'),null);
 form=mount();form.querySelector('[name=title]').name='different-purpose';await tick();assert.equal(form.querySelector('[data-session-recovery]'),null);
 document.querySelector('nav').setAttribute('data-user-id','owner-b');form=mount();await tick();assert.equal(form.querySelector('[data-session-recovery]'),null);
 document.querySelector('nav').setAttribute('data-user-id','owner-a');form=mount();await tick();
 const panel=form.querySelector('[data-session-recovery]');assert.ok(panel);
 panel.querySelector('button').click();
 assert.equal(form.querySelector('[name=title]').value,'Unsaved title');assert.equal(form.querySelector('[name=notes]').value,'Unsaved notes');assert.equal(form.querySelector('[name=password]').value,'');assert.ok(!form.querySelector('[name=consent]').checked);
 assert.ok(panel.textContent.includes('Latest saved value'));
 assert.equal(form.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true})),false);
 panel.querySelector('input[type=checkbox]').checked=true;
 assert.equal(form.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true})),true);
 assert.ok(values.size>0,'a submission alone must not erase the draft');
 assert.equal(window.CRMSessionDrafts.saved(form,{offline:true}),false,'a queued offline write is not a confirmed server save');
 assert.ok(values.size>0);
 form.querySelector('[name=title]').value='Newer unsaved edit';form.querySelector('[name=title]').dispatchEvent(new window.Event('input',{bubbles:true}));
 assert.equal(window.CRMSessionDrafts.saved(form),false,'an older save must not delete newer edits');
 assert.ok([...values.values()].some(value=>value.includes('Newer unsaved edit')));
 form.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
 assert.equal(window.CRMSessionDrafts.saved(form),true);
 assert.equal(values.size,0);
 form.querySelector('[name=title]').dispatchEvent(new window.Event('input',{bubbles:true}));assert.equal(values.size,0,'a retired recovery panel must not recreate a saved draft');
 form=mount();await tick();assert.equal(form.querySelector('[data-session-recovery]'),null,'saved drafts are not offered again');
});
